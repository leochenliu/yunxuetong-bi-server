"""schema.sql 与事实库结构的一致性校验。

`sql/schema.sql` 是建表结构的**单一事实源**，`src/bi/store.py` 从它加载 DDL。
这些测试守住三件事：
  1) 文件存在且确实被 store 加载；
  2) 用文件重建的库 == 用 `init_schema()` 建的库（表 / 列 / 索引 / 视图完全一致）；
  3) 本地在用的 SQLite 库没有和文件漂移（存在时才对账）。
"""

from __future__ import annotations

import sqlite3
from pathlib import Path

import pytest

from bi.store import POSTGRES_SCHEMA, SCHEMA, SCHEMA_PATH, FactStore

FACT_TABLES = {
    "upload_versions",
    "raw_records",
    "diff_events",
    "metric_snapshots",
    "metric_buckets",
    "anomalies",
    "audit_log",
}

# 本地实体表（由 scripts/build_entity_tables.py 从 raw_records 投影，不参与 ingest/差分）
ENTITY_TABLES = {
    "certificates",
    "students",
    "companies",
}

# 定时任务执行记录（一天一 job 一行；漏跑 = 没有这一行）
JOB_TABLES = {
    "job_runs",
}

# 不再有外部系统镜像表（trainingos_* 已全部移除）：见 schema.sql「不镜像外部系统的表」
# 也不再建视图：辅助视图没有代码使用，只是多一层要跟表结构同步的对象


def _structure(db_path: Path) -> dict:
    """抓取库的结构快照（表列 / 索引 / 视图）。"""
    conn = sqlite3.connect(db_path)
    try:
        tables = {}
        for (name,) in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
        ).fetchall():
            # (列名, 类型, 是否非空, 默认值)
            tables[name] = [
                (row[1], row[2].upper(), bool(row[3]), row[4])
                for row in conn.execute(f"PRAGMA table_info({name})").fetchall()
            ]
        indexes = sorted(
            row[0]
            for row in conn.execute(
                "SELECT name FROM sqlite_master WHERE type='index' AND name NOT LIKE 'sqlite_%'"
            ).fetchall()
        )
        views = sorted(
            row[0]
            for row in conn.execute("SELECT name FROM sqlite_master WHERE type='view'").fetchall()
        )
        return {"tables": tables, "indexes": indexes, "views": views}
    finally:
        conn.close()


def test_schema_file_is_the_source_of_truth():
    assert SCHEMA_PATH.is_file(), f"缺少建表脚本：{SCHEMA_PATH}"
    assert SCHEMA == SCHEMA_PATH.read_text(encoding="utf-8")
    for table in FACT_TABLES | ENTITY_TABLES | JOB_TABLES:
        assert f"CREATE TABLE IF NOT EXISTS {table}" in SCHEMA


def test_job_runs_is_one_row_per_day():
    """job_runs 一天一行：唯一约束 + status 只允许三种（不含 missed）。"""
    block = SCHEMA.split("CREATE TABLE IF NOT EXISTS job_runs")[1].split(");")[0]
    assert "UNIQUE (job_id, run_date)" in block
    for status in ("success", "partial", "failed"):
        assert f"'{status}'" in block
    assert "'missed'" not in block, "漏跑由「没有行」表达，不写 missed 记录"
    assert "attempts" not in block, "同一天重跑只覆盖，不累加计数（幂等）"


def test_entity_tables_are_in_the_same_database_as_facts():
    """实体表与事实表同库：不再单独一个 sqlite 文件。

    `scripts/build_entity_tables.py` 的 DDL 也必须在 schema.sql 里，
    否则脚本会自己写一份 DDL，两边必然漂移。
    """
    script = (Path(__file__).resolve().parents[1] / "scripts"
              / "build_entity_tables.py").read_text(encoding="utf-8")
    assert "CREATE TABLE" not in script.upper(), "脚本里不许再写 DDL，只从 schema.sql 建表"
    for table in ENTITY_TABLES:
        assert f"CREATE TABLE IF NOT EXISTS {table}" in SCHEMA


def test_no_external_mirror_tables():
    """库里不镜像任何外部系统的表（`trainingos_*` 已全部移除）。

    镜像会同时带来三个问题：同一个问题有两套答案（源库 UUID 口径 vs 台账公司名口径）、
    快照必然过时、PII 面积翻倍。要重新引入外部表，先在这里明确写出理由。
    """
    for line in SCHEMA.splitlines():
        if line.strip().upper().startswith("CREATE TABLE"):
            assert "trainingos_" not in line.lower(), f"不允许再建镜像表：{line.strip()}"


def test_schema_file_rebuilds_same_structure_as_init_schema(tmp_path):
    from_file_db = tmp_path / "from_file.sqlite3"
    conn = sqlite3.connect(from_file_db)
    try:
        conn.executescript(SCHEMA)
    finally:
        conn.close()

    from_store_db = tmp_path / "from_store.sqlite3"
    FactStore(db_path=from_store_db).init_schema()

    assert _structure(from_file_db) == _structure(from_store_db)


def test_schema_defines_no_views(tmp_path):
    """schema.sql 不建视图。

    视图没有代码查询（只有文档与人工排查用），却要在每次改表时同步，
    还会让「某个数字从哪来」多一层转发。要排查请直接查表或走 API。
    """
    assert "CREATE VIEW" not in SCHEMA.upper()
    db = tmp_path / "views.sqlite3"
    conn = sqlite3.connect(db)
    try:
        conn.executescript(SCHEMA)
        views = conn.execute("SELECT name FROM sqlite_master WHERE type='view'").fetchall()
        assert views == []
    finally:
        conn.close()


def test_postgres_schema_derived_from_file_is_clean():
    from bi.store import _split_statements

    assert "PRAGMA" not in POSTGRES_SCHEMA
    assert "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in POSTGRES_SCHEMA
    statements = _split_statements(POSTGRES_SCHEMA)
    assert statements, "PostgreSQL 方言应能切出语句"
    for stmt in statements:
        assert stmt.upper().startswith("CREATE"), stmt[:60]


@pytest.mark.skipif(
    not (Path(__file__).resolve().parents[1] / "data" / "store" / "bi.sqlite3").is_file(),
    reason="本地事实库不存在（data/store/ 已 gitignore），跳过对账",
)
def test_local_database_has_not_drifted_from_schema_file(tmp_path):
    """本地在用的 SQLite 库必须与 schema.sql 的表结构一致。"""
    live_db = Path(__file__).resolve().parents[1] / "data" / "store" / "bi.sqlite3"
    reference_db = tmp_path / "reference.sqlite3"
    conn = sqlite3.connect(reference_db)
    try:
        conn.executescript(SCHEMA)
    finally:
        conn.close()

    live = _structure(live_db)
    reference = _structure(reference_db)
    assert live["tables"] == reference["tables"]
    assert live["indexes"] == reference["indexes"]
    assert live["views"] == reference["views"] == []
